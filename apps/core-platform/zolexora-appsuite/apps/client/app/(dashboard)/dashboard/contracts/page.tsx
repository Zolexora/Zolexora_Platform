import Link from 'next/link'
import { getCurrentUser } from '@/lib/auth'
import { query } from '@/lib/db'
import { Badge, contractStatusColor } from '@/components/ui/badge'
import { Card } from '@/components/ui/card'
import { CONTRACT_STATUS_LABELS, type Contract } from '@/lib/types'
import { FileText, ExternalLink } from 'lucide-react'

export const metadata = { title: 'Contracts' }

export default async function ContractsPage() {
  const user = await getCurrentUser()
  const userId = user?.id

  const { rows: contracts } = userId
    ? await query<Contract>(
        'SELECT * FROM public.contracts WHERE user_id = $1 ORDER BY created_at DESC',
        [userId]
      )
    : { rows: [] as Contract[] }

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold text-white">
          Contracts
        </h1>
        <p className="text-sm text-[#CBD5E1]/70 mt-1">
          Review and track your project contracts and agreements.
        </p>
      </div>

      {!contracts || contracts.length === 0 ? (
        <Card className="py-16 text-center bg-[#0A0A0A] border border-[#404040]">
          <FileText className="w-10 h-10 text-[#CBD5E1]/50 mx-auto mb-4" />
          <h3 className="font-semibold text-white mb-2">
            No contracts yet
          </h3>
          <p className="text-sm text-[#CBD5E1]/70 max-w-sm mx-auto">
            Contracts are generated by our team after your project request is
            reviewed and approved. Check back here once you&apos;ve received a proposal.
          </p>
        </Card>
      ) : (
        <div className="flex flex-col gap-3">
          {contracts.map((contract: Contract) => (
            <Link
              key={contract.id}
              href={`/dashboard/contracts/${contract.id}`}
              className="block rounded-xl border border-[#404040] bg-[#0A0A0A] p-5 hover:border-[#CBD5E1]/50 hover:bg-[#121824] transition-all group"
            >
              <div className="flex items-center justify-between gap-4">
                <div className="flex items-center gap-3 min-w-0">
                  <div className="w-9 h-9 rounded-lg bg-[#0B1F3A] border border-[#CBD5E1]/30 flex items-center justify-center shrink-0">
                    <FileText className="w-4 h-4 text-[#CBD5E1]" />
                  </div>
                  <div className="min-w-0">
                    <p className="font-semibold text-white group-hover:text-[#CBD5E1] transition-colors truncate">
                      {contract.title}
                    </p>
                    <p className="text-xs text-[#CBD5E1]/60 mt-0.5">
                      {new Date(contract.created_at).toLocaleDateString(
                        'en-IN',
                        {
                          day: 'numeric',
                          month: 'short',
                          year: 'numeric',
                        }
                      )}
                      {contract.signed_at && (
                        <> · Signed {new Date(contract.signed_at).toLocaleDateString('en-IN', { day: 'numeric', month: 'short' })}</>
                      )}
                    </p>
                  </div>
                </div>
                <div className="flex items-center gap-3 shrink-0">
                  <Badge color={contractStatusColor[contract.status]}>
                    {CONTRACT_STATUS_LABELS[contract.status]}
                  </Badge>
                  {contract.document_url && (
                    <ExternalLink className="w-4 h-4 text-[#CBD5E1]/70" />
                  )}
                </div>
              </div>
            </Link>
          ))}
        </div>
      )}
    </div>
  )
}
